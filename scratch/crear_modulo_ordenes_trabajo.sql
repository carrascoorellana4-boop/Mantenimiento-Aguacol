-- ====================================================================
-- SCRIPT ADMINISTRATIVO: MÓDULO DE ÓRDENES DE TRABAJO (KANBAN + FICHA + AUDITORÍA + REALTIME)
-- Archivo: scratch/crear_modulo_ordenes_trabajo.sql
-- Ejecutar en: Supabase SQL Editor (Rol postgres)
-- Proyecto: Sistema_Mantenimiento (AGUACOL)
-- Principio Fundamental:
--   Una sola fuente de verdad: public.orden_trabajo.estado ('Pendiente', 'En curso', 'Finalizada')
--   Validación estricta en BD: No permitir estado = 'Finalizada' sin solucion_definitiva.
--   Trazabilidad completa en public.orden_trabajo_estado_historial y vínculo ot_id con bitacora_mantenimiento.
-- ====================================================================

BEGIN;

-- --------------------------------------------------------------------
-- 1. TABLA PRINCIPAL: public.orden_trabajo
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.orden_trabajo (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    numero_ot bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    codigo_ot text GENERATED ALWAYS AS ('OT-' || lpad(numero_ot::text, 6, '0')) STORED,
    equipo_id uuid REFERENCES public.equipo(id) ON DELETE SET NULL,
    ubicacion text,
    area text,
    trabajo text NOT NULL,
    tecnico text,
    estado text NOT NULL DEFAULT 'Pendiente',
    origen text NOT NULL DEFAULT 'Manual',
    prioridad text NOT NULL DEFAULT 'Media',
    tipo_intervencion text DEFAULT 'Correctiva',
    es_falla boolean NOT NULL DEFAULT true,
    tipo_falla text,
    solucion_definitiva text,
    trabajo_pendiente text,
    fecha_reporte timestamptz NOT NULL DEFAULT now(),
    fecha_inicio timestamptz,
    fecha_finalizacion timestamptz,
    created_by uuid DEFAULT auth.uid(),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),

    -- Restricción 1: Solo los 3 estados oficiales (Una sola fuente de verdad)
    CONSTRAINT chk_orden_trabajo_estado CHECK (
        estado IN ('Pendiente', 'En curso', 'Finalizada')
    ),

    -- Restricción 2: Orígenes soportados (Manual, Inspección, WhatsApp)
    CONSTRAINT chk_orden_trabajo_origen CHECK (
        origen IN ('Manual', 'Inspección', 'WhatsApp')
    ),

    -- Restricción 3: REGLA ESTRICTA (#5) - No permitir finalizar sin solución definitiva
    CONSTRAINT chk_ot_solucion_requerida_al_finalizar CHECK (
        estado <> 'Finalizada'
        OR (solucion_definitiva IS NOT NULL AND btrim(solucion_definitiva) <> '')
    )
);

CREATE INDEX IF NOT EXISTS idx_orden_trabajo_estado ON public.orden_trabajo(estado);
CREATE INDEX IF NOT EXISTS idx_orden_trabajo_equipo_id ON public.orden_trabajo(equipo_id);
CREATE INDEX IF NOT EXISTS idx_orden_trabajo_fecha_reporte ON public.orden_trabajo(fecha_reporte DESC);
CREATE INDEX IF NOT EXISTS idx_orden_trabajo_fecha_finalizacion ON public.orden_trabajo(fecha_finalizacion DESC);

-- --------------------------------------------------------------------
-- 2. TABLA DE AUDITORÍA DE ESTADOS: public.orden_trabajo_estado_historial (#16)
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.orden_trabajo_estado_historial (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    ot_id uuid NOT NULL REFERENCES public.orden_trabajo(id) ON DELETE CASCADE,
    estado_anterior text,
    estado_nuevo text NOT NULL,
    fecha_hora timestamptz NOT NULL DEFAULT now(),
    usuario_id uuid DEFAULT auth.uid(),
    usuario_nombre text,
    comentario text,

    CONSTRAINT chk_ot_historial_estado_nuevo CHECK (
        estado_nuevo IN ('Pendiente', 'En curso', 'Finalizada')
    )
);

CREATE INDEX IF NOT EXISTS idx_ot_estado_historial_ot_id ON public.orden_trabajo_estado_historial(ot_id, fecha_hora DESC);

-- --------------------------------------------------------------------
-- 3. TRIGGER DE UPDATED_AT Y VALIDACIÓN DE SEGURIDAD EN BD
-- --------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.trg_fn_orden_trabajo_before_write()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := now();

    -- Regla 3: Pendiente -> En curso asigna fecha_inicio si es NULL, conserva si ya existía
    IF NEW.estado = 'En curso' AND NEW.fecha_inicio IS NULL THEN
        NEW.fecha_inicio := now();
    END IF;

    -- Regla 5: No permitir Finalizada sin solucion_definitiva
    IF NEW.estado = 'Finalizada' THEN
        IF NEW.solucion_definitiva IS NULL OR btrim(NEW.solucion_definitiva) = '' THEN
            RAISE EXCEPTION 'No es posible finalizar la OT sin registrar una solución definitiva.';
        END IF;
        IF NEW.fecha_finalizacion IS NULL THEN
            NEW.fecha_finalizacion := now();
        END IF;
    END IF;

    -- Regla 6: Si se reabre (Finalizada -> En curso) o vuelve a Pendiente, limpiar fecha_finalizacion
    IF TG_OP = 'UPDATE' AND OLD.estado = 'Finalizada' AND NEW.estado <> 'Finalizada' THEN
        NEW.fecha_finalizacion := NULL;
    END IF;

    -- Regla 7: En curso -> Pendiente conserva fecha_inicio histórica
    IF TG_OP = 'UPDATE' AND OLD.fecha_inicio IS NOT NULL AND NEW.fecha_inicio IS NULL THEN
        NEW.fecha_inicio := OLD.fecha_inicio;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_orden_trabajo_before_write ON public.orden_trabajo;
CREATE TRIGGER trg_orden_trabajo_before_write
BEFORE INSERT OR UPDATE ON public.orden_trabajo
FOR EACH ROW
EXECUTE FUNCTION public.trg_fn_orden_trabajo_before_write();

-- --------------------------------------------------------------------
-- 4. RPC OFICIAL PARA CAMBIO DE ESTADO SINCRONIZADO (#5, #8, #16)
-- --------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.cambiar_estado_orden_trabajo(
    p_ot_id uuid,
    p_nuevo_estado text,
    p_solucion_definitiva text DEFAULT NULL,
    p_trabajo_pendiente text DEFAULT NULL,
    p_tecnico text DEFAULT NULL,
    p_comentario text DEFAULT NULL,
    p_usuario_nombre text DEFAULT NULL
)
RETURNS public.orden_trabajo
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_actual public.orden_trabajo;
    v_actualizada public.orden_trabajo;
    v_solucion_final text;
    v_trabajo_pend_final text;
    v_tecnico_final text;
    v_fecha_inicio_final timestamptz;
    v_fecha_fin_final timestamptz;
BEGIN
    IF p_nuevo_estado NOT IN ('Pendiente', 'En curso', 'Finalizada') THEN
        RAISE EXCEPTION 'Estado inválido: %. Los valores permitidos son Pendiente, En curso, Finalizada.', p_nuevo_estado;
    END IF;

    SELECT * INTO v_actual
    FROM public.orden_trabajo
    WHERE id = p_ot_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'No se encontró la Orden de Trabajo especificada (%).', p_ot_id;
    END IF;

    v_solucion_final := COALESCE(NULLIF(btrim(p_solucion_definitiva), ''), v_actual.solucion_definitiva);
    v_trabajo_pend_final := CASE
        WHEN p_trabajo_pendiente IS NOT NULL THEN NULLIF(btrim(p_trabajo_pendiente), '')
        ELSE v_actual.trabajo_pendiente
    END;
    v_tecnico_final := COALESCE(NULLIF(btrim(p_tecnico), ''), v_actual.tecnico);
    v_fecha_inicio_final := v_actual.fecha_inicio;
    v_fecha_fin_final := v_actual.fecha_finalizacion;

    -- Regla 3: Al pasar a En curso, asignar fecha_inicio si es NULL y conservar existente
    IF p_nuevo_estado = 'En curso' THEN
        v_fecha_inicio_final := COALESCE(v_actual.fecha_inicio, now());
        v_fecha_fin_final := NULL;
    ELSIF p_nuevo_estado = 'Finalizada' THEN
        -- Regla 4 y 5: Validar solución definitiva obligatoria
        IF v_solucion_final IS NULL OR btrim(v_solucion_final) = '' THEN
            RAISE EXCEPTION 'No es posible finalizar la OT sin registrar una solución definitiva.';
        END IF;
        v_fecha_inicio_final := COALESCE(v_actual.fecha_inicio, now());
        v_fecha_fin_final := now();
    ELSIF p_nuevo_estado = 'Pendiente' THEN
        -- Regla 7: Conservar fecha_inicio por trazabilidad, limpiar fecha_finalizacion
        v_fecha_fin_final := NULL;
    END IF;

    UPDATE public.orden_trabajo
    SET estado = p_nuevo_estado,
        solucion_definitiva = v_solucion_final,
        trabajo_pendiente = v_trabajo_pend_final,
        tecnico = v_tecnico_final,
        fecha_inicio = v_fecha_inicio_final,
        fecha_finalizacion = v_fecha_fin_final,
        updated_at = now()
    WHERE id = p_ot_id
    RETURNING * INTO v_actualizada;

    -- Registrar en auditoría si cambió el estado o si se documentó un comentario
    IF v_actual.estado IS DISTINCT FROM p_nuevo_estado OR p_comentario IS NOT NULL THEN
        INSERT INTO public.orden_trabajo_estado_historial (
            ot_id,
            estado_anterior,
            estado_nuevo,
            fecha_hora,
            usuario_id,
            usuario_nombre,
            comentario
        ) VALUES (
            p_ot_id,
            v_actual.estado,
            p_nuevo_estado,
            now(),
            auth.uid(),
            COALESCE(NULLIF(btrim(p_usuario_nombre), ''), v_tecnico_final, 'Usuario del sistema'),
            p_comentario
        );
    END IF;

    RETURN v_actualizada;
END;
$$;

-- --------------------------------------------------------------------
-- 5. PERMISOS Y POLÍTICAS RLS
-- --------------------------------------------------------------------
ALTER TABLE public.orden_trabajo ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orden_trabajo_estado_historial ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir lectura de OT a usuarios autenticados y anon" ON public.orden_trabajo;
CREATE POLICY "Permitir lectura de OT a usuarios autenticados y anon"
ON public.orden_trabajo FOR SELECT
TO authenticated, anon
USING (true);

DROP POLICY IF EXISTS "Permitir insercion de OT a usuarios autenticados y anon" ON public.orden_trabajo;
CREATE POLICY "Permitir insercion de OT a usuarios autenticados y anon"
ON public.orden_trabajo FOR INSERT
TO authenticated, anon
WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir actualizacion de OT a usuarios autenticados y anon" ON public.orden_trabajo;
CREATE POLICY "Permitir actualizacion de OT a usuarios autenticados y anon"
ON public.orden_trabajo FOR UPDATE
TO authenticated, anon
USING (true)
WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir lectura de historial OT" ON public.orden_trabajo_estado_historial;
CREATE POLICY "Permitir lectura de historial OT"
ON public.orden_trabajo_estado_historial FOR SELECT
TO authenticated, anon
USING (true);

DROP POLICY IF EXISTS "Permitir insercion de historial OT" ON public.orden_trabajo_estado_historial;
CREATE POLICY "Permitir insercion de historial OT"
ON public.orden_trabajo_estado_historial FOR INSERT
TO authenticated, anon
WITH CHECK (true);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.orden_trabajo TO authenticated, anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.orden_trabajo_estado_historial TO authenticated, anon;
GRANT USAGE, SELECT ON SEQUENCE public.orden_trabajo_numero_ot_seq TO authenticated, anon;
GRANT EXECUTE ON FUNCTION public.cambiar_estado_orden_trabajo(uuid, text, text, text, text, text, text) TO authenticated, anon;

-- --------------------------------------------------------------------
-- 6. HABILITAR SUPABASE REALTIME (#10)
-- --------------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables
        WHERE pubname = 'supabase_realtime'
          AND schemaname = 'public'
          AND tablename = 'orden_trabajo'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.orden_trabajo;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables
        WHERE pubname = 'supabase_realtime'
          AND schemaname = 'public'
          AND tablename = 'orden_trabajo_estado_historial'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.orden_trabajo_estado_historial;
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        RAISE NOTICE 'Publicación supabase_realtime no modificada: %', SQLERRM;
END $$;

COMMIT;

